"""Export the scene groupings to a JSON file Unity can read, plus the art plan.

Reads build/scenes_layout.json and build/scene_art.json (hand-written names and look briefs) and writes:
- Game/EverythingWorld/Assets/_Project/Data/scenes.json with, per scene: id, name, realm, tags,
  position/radius, sound averages, look brief and its tracks (name, artist, Spotify ID).
- ART_PLAN.md, a readable version of the names and look briefs.

Only public info goes in (track names, artists, IDs), never the "Added By" usernames.
Rerun after scenes.py / layout_scenes.py:  python build/export_unity.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "build" / "scenes_layout.json"
ART = ROOT / "build" / "scene_art.json"
DST = ROOT / "Game" / "EverythingWorld" / "Assets" / "_Project" / "Data" / "scenes.json"
PLAN = ROOT / "ART_PLAN.md"
CSV = ROOT / "build" / "playlist.csv"  # only the track URI and duration columns are read
DEFAULT_MS = 210000
BRIEF_FIELDS = ("terrain", "palette", "landmark", "props", "mood")


def load_art(layout):
    """Names and briefs by scene id. Warns when a scene no longer holds its anchor artists."""
    art = json.loads(ART.read_text(encoding="utf-8"))
    scene_art = {a["id"]: a for a in art["scenes"]}
    for s in layout["scenes"]:
        a = scene_art.get(s["id"])
        if a is None:
            print(f"warning: scene {s['id']} has no name in scene_art.json")
        elif not set(a["anchors"]) & set(s["artists"]):
            print(f"warning: scene {s['id']} ({a['name']}) no longer contains its anchor artists "
                  f"{a['anchors']}; scene ids may have changed, check scene_art.json")
    return {r["id"]: r for r in art["realms"]}, scene_art


def write_plan(scenes, realms):
    out = ["# Everything World art plan", "",
           "Generated by `build/export_unity.py` from `build/scene_art.json`. Edit the JSON, not this file.", "",
           "Each scene's look follows its music: louder scenes get higher, sharper terrain; acoustic scenes get more plants and wood; "
           "happier scenes get brighter, warmer colours.", ""]
    for rid in sorted(realms):
        r = realms[rid]
        out += [f"## {r['name']}", "", r["note"], ""]
        for s in scenes:
            if s["realm"] != rid:
                continue
            out += [f"### {s['id']}. {s['name']}", "",
                    f"*{', '.join(s['tags'][:5])}* · {len(s['tracks'])} songs · "
                    f"energy {s['energy']:.2f}, acoustic {s['acousticness']:.2f}, mood {s['valence']:.2f} · "
                    f"top artists: {', '.join(s['artists'][:5])}", "",
                    f"- **Terrain:** {s['terrain']}",
                    f"- **Colours:** {', '.join(f'`{c}`' for c in s['palette'])}",
                    f"- **Landmark:** {s['landmark']}",
                    f"- **Props:** {s['props']}",
                    f"- **Light and mood:** {s['mood']}", ""]
    PLAN.write_text("\n".join(out), encoding="utf-8", newline="\n")


from stations import HUB_ID, artist_station, ARTIST_MIN_SONGS


def load_feel():
    """Track ID -> (energy, valence) 0..1, from the Exportify CSV (the world's lights follow the music)."""
    if not CSV.exists():
        return {}
    def num(x):
        try: return round(float(x), 3)
        except (TypeError, ValueError): return .5
    with CSV.open(encoding="utf-8-sig", newline="") as f:
        return {row["Track URI"].rsplit(":", 1)[-1]: (num(row.get("Energy")), num(row.get("Valence"))) for row in csv.DictReader(f)}


def load_durations():
    """Track ID -> length in ms, from the Exportify CSV (the zone radio needs song lengths)."""
    if not CSV.exists():
        print(f"warning: {CSV.name} not found; every song gets a default length of {DEFAULT_MS // 1000} s")
        return {}
    with CSV.open(encoding="utf-8-sig", newline="") as f:
        return {row["Track URI"].rsplit(":", 1)[-1]: int(row["Duration (ms)"])
                for row in csv.DictReader(f) if row.get("Duration (ms)")}


def main():
    layout = json.loads(SRC.read_text(encoding="utf-8"))
    durations = load_durations()
    feel = load_feel()
    realms, scene_art = load_art(layout)
    artist_scene = {name: a["scene"] for name, a in layout["artists"].items()}

    tracks = {s["id"]: [] for s in layout["scenes"]}
    missing = no_length = 0
    for name, artist, track_id in layout["songs"]:
        scene = artist_scene.get(artist)
        if scene is None:
            missing += 1
            continue
        if track_id not in durations:
            no_length += 1
        tracks[scene].append({"name": name, "artist": artist, "id": track_id,
                              "duration_ms": durations.get(track_id, DEFAULT_MS),
                              "energy": feel.get(track_id, (.5, .5))[0], "valence": feel.get(track_id, (.5, .5))[1]})

    scenes = []
    for s in layout["scenes"]:
        a = scene_art.get(s["id"], {})
        scenes.append({
            "id": s["id"],
            "name": a.get("name", ""),
            "realm": s["realm"],
            "realmName": realms.get(s["realm"], {}).get("name", ""),
            "tags": s["tags"],
            "x": s["x"],
            "y": s["y"],
            "r": s["r"],
            "energy": s["sound"]["energy"],
            "acousticness": s["sound"]["acousticness"],
            "valence": s["sound"]["valence"],
            "danceability": s["sound"]["danceability"],
            "tempo": s["sound"]["tempo"],
            "neighbours": s["neighbours"],
            **{f: a.get(f, [] if f == "palette" else "") for f in BRIEF_FIELDS},
            "tracks": sorted(tracks[s["id"]], key=lambda t: (t["artist"].lower(), t["name"].lower(), t["id"])),
        })

    write_plan([dict(sc, artists=s["artists"]) for sc, s in zip(scenes, layout["scenes"])], realms)

    # The Everything Hub: a small island of its own whose station plays the whole playlist.
    every = sorted((t for s in scenes for t in s["tracks"]), key=lambda t: (t["artist"].lower(), t["name"].lower(), t["id"]))
    scenes.append({"id": HUB_ID, "name": "The Everything Hub", "realm": -1, "realmName": "", "tags": [],
                   "x": 0, "y": 0, "r": 0, "energy": 0, "acousticness": 0, "valence": 0, "danceability": 0, "tempo": 0,
                   "neighbours": [], **{f: [] if f == "palette" else "" for f in BRIEF_FIELDS},
                   "mood": "Everything, shuffled.", "tracks": every})

    # Artist stations: every artist with 3+ songs plays only their own songs while you stand in their area.
    by_artist = {}
    for t in every:
        by_artist.setdefault(t["artist"], []).append(t)
    ids = {}
    for name, ts in sorted(by_artist.items()):
        if len(ts) < ARTIST_MIN_SONGS:
            continue
        sid = artist_station(name)
        assert sid not in ids, f"station id clash: {name} and {ids[sid]}"
        ids[sid] = name
        scenes.append({"id": sid, "name": name, "realm": -1, "realmName": "", "tags": [],
                       "x": 0, "y": 0, "r": 0, "energy": 0, "acousticness": 0, "valence": 0, "danceability": 0, "tempo": 0,
                       "neighbours": [], **{f: [] if f == "palette" else "" for f in BRIEF_FIELDS},
                       "mood": "Artist radio.", "tracks": ts})

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(json.dumps({"scenes": scenes}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    total = sum(len(s["tracks"]) for s in scenes if s["id"] < HUB_ID)
    print(f"Wrote {sum(1 for s in scenes if s['id'] < HUB_ID)} scenes, the hub, {len(ids)} artist stations, {total} tracks to {DST.relative_to(ROOT)} and {PLAN.name}"
          + (f" ({missing} songs had no scene)" if missing else "")
          + (f" ({no_length} songs had no length, used {DEFAULT_MS // 1000} s)" if no_length else ""))


if __name__ == "__main__":
    main()
